"""Labelled lines for the credential screen: release gate B5.

Each entry is (file suffix, text). A credential word is written as a marker such as @pw@ and
spelled out by `spell`, so no string in this file pairs a credential label with a value, and the
repository's own scan reads this file like any other. Every value is synthetic.

MUST_PASS    the field is given a variable, a call, an environment lookup or an expansion.
MUST_REFUSE  the field is given a literal, directly or as what it falls back to.
KNOWN_FALSE_REFUSALS and KNOWN_MISSES are what the screen still gets wrong, each with the reason.
They are tested as they behave today, so a change to either is seen.
"""

WORDS = {
    "@pw@": "pass" + "word", "@Pw@": "Pass" + "word", "@PW@": "PASS" + "WORD",
    "@ak@": "api_" + "key", "@aK@": "api" + "Key", "@Ak@": "Api" + "Key", "@AK@": "API_" + "KEY",
    "@sec@": "sec" + "ret", "@Sec@": "Sec" + "ret", "@SEC@": "SEC" + "RET",
    "@at@": "access_" + "token", "@aT@": "access" + "Token",
    "@sK@": "signing" + "Key", "@pk@": "private_" + "key", "@ght@": "github_" + "token",
    "@V@": "".join(["Zq7Lm2", "Xp9Rt4", "Vw8"]),       # a value of letters and digits
    "@W@": "-".join(["tangerine", "walrus", "orbit"]),  # a value of words
}


def spell(text: str) -> str:
    for marker, word in WORDS.items():
        text = text.replace(marker, word)
    return text


